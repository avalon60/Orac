from __future__ import annotations

import argparse
import csv
import logging
from pathlib import Path
from tempfile import TemporaryDirectory
import sys

# Support direct execution and imports through the plugin-local tools package.
if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from tools.generate_seed import (  # noqa: E402
    GAMBIT_COLUMNS,
    OPENING_COLUMNS,
    ROOT,
    VIDEO_OPTIONAL,
    VIDEO_REQUIRED,
    generate,
)

logger = logging.getLogger(__name__)

PREFIX = "__SEED_ACCEPTANCE_"


def block(
    label: str,
    pgn: str = "1.e4 {" + "x" * 40000 + "} e5 *",
    fen: str = "",
    missing: bool = False,
) -> str:
    """Generate a genuine runtime block from isolated CSV fixtures.

    Args:
        label: Batch suffix distinguishing fixture identities.
        pgn: Root mainline notation passed to the production validator.
        fen: Optional starting position passed to the production validator.
        missing: Include a deliberately absent video link target.

    Returns:
        Nested PL/SQL without SQLcl delimiters or Liquibase metadata.
    """
    with TemporaryDirectory() as directory:
        batch = Path(directory) / ("acceptance_" + label)
        batch.mkdir()
        name = PREFIX + label
        files = {
            "openings.csv": (
                OPENING_COLUMNS,
                [
                    {
                        "name": name + "_child",
                        "parent_opening_name": name + "_parent",
                        "description": "original child",
                        "eco_codes": "A00|B00",
                        "aliases": "one|two",
                        "mainline_name": "Original root",
                        "mainline_pgn": pgn,
                        "starting_fen": fen,
                    },
                    {"name": name + "_parent"},
                ],
            ),
            "gambits.csv": (
                GAMBIT_COLUMNS,
                [
                    {
                        "name": name + "_gambit",
                        "opening_names": name + "_parent|" + name + "_child",
                    }
                ],
            ),
            "videos.csv": (
                VIDEO_REQUIRED + VIDEO_OPTIONAL,
                [
                    {
                        "Platform": "Fixture",
                        "Creator": name,
                        "Title": "Original title",
                        "External Video Id": name,
                        "Video URL": "https://example.test/" + label,
                        "Description": '  Unicode ♞ "quote"\nprose  ',
                        "Opening Names": name + ("_missing" if missing else "_child"),
                        "Gambit Names": name + "_gambit",
                    }
                ],
            ),
        }
        for filename, (columns, rows) in files.items():
            with (batch / filename).open("w", encoding="utf-8", newline="") as stream:
                writer = csv.DictWriter(stream, columns)
                writer.writeheader()
                writer.writerows(rows)
        sql = generate(batch)
        return sql[sql.index("declare\n") : sql.index("\n/\n")]


def generate_acceptance() -> str:
    """Build reproducible rollback-only success, preservation and atomicity checks."""
    valid = block("valid")
    text = """-- Author: Clive Bostock
-- Date: 07-Nov-2026
-- Purpose: Exercise actual generated batch runtime on an explicitly isolated test install.
-- Usage: Set client_identifier to ORAC_CHESS_SEED_ISOLATED_ACCEPTANCE, then SQLcl @this-file.
-- Generated by tools/generate_seed_acceptance.py; never included by install controllers.
-- Do not run against existing DEV. Caller must separately authorise an isolated installed database.
whenever sqlerror exit failure rollback
set define off
set sqlblanklines on
set serveroutput on
declare
  l_id number;
  l_root number;
  l_version number;
  l_next number;
  l_count number;
  procedure expect(p_ok boolean, p_message varchar2) is
  begin
    if p_ok is null or not p_ok
    then
      raise_application_error(-20999,p_message);
    end if;
  end;
begin
  if sys_context('userenv','client_identifier') <> 'ORAC_CHESS_SEED_ISOLATED_ACCEPTANCE'
     or sys_context('userenv','client_identifier') is null
  then
    raise_application_error(-20998,'Requires explicit isolated seed acceptance opt-in');
  end if;
  savepoint seed_acceptance;
  select count(*) into l_count from orac_chess.chess_content_source_v where creator like '__SEED_ACCEPTANCE_%';
  expect(l_count = 0,'Acceptance fixture identities already exist');
"""
    text += valid + "\n"
    text += """  select count(*) into l_count from orac_chess.chess_variation_v
  where opening_id = (select opening_id from orac_chess.chess_opening_v where name = '__SEED_ACCEPTANCE_valid_child')
    and dbms_lob.getlength(pgn) > 40000;
  expect(l_count = 1,'Long mainline CLOB must survive JSON and public API validation');
  select opening_id,row_version into l_id,l_version from orac_chess.chess_opening_v where name = '__SEED_ACCEPTANCE_valid_child';
  orac_chess.chess_admin_api.save_opening(l_id,l_version,'__SEED_ACCEPTANCE_valid_child','SYSTEM',to_clob('User description'),null,l_next);
  select variation_id,row_version into l_root,l_version from orac_chess.chess_variation_v where opening_id = l_id and parent_variation_id is null;
  orac_chess.chess_variation_api.save_variation(l_root,l_version,l_id,null,null,null,'User root','MAIN',to_clob('1.d4 d5 *'),null,to_clob('User annotation'),l_next);
  select row_version into l_version from orac_chess.chess_content_source_v where creator = '__SEED_ACCEPTANCE_valid';
  orac_chess.chess_admin_api.save_content_source('__SEED_ACCEPTANCE_valid',l_version,'__SEED_ACCEPTANCE_valid','User author',to_clob('User notes'),l_next);
  select video_id,row_version into l_id,l_version from orac_chess.chess_video_v where platform = 'Fixture' and external_video_id = '__SEED_ACCEPTANCE_valid';
  orac_chess.chess_admin_api.save_video(l_id,l_version,'Fixture','__SEED_ACCEPTANCE_valid','https://example.test/user','User title','__SEED_ACCEPTANCE_valid',to_clob('User prose'),12,date '2024-01-01',l_next);
"""
    text += valid + "\n"
    text += """  select count(*) into l_count from orac_chess.chess_opening_v
  where name = '__SEED_ACCEPTANCE_valid_child' and opening_type = 'SYSTEM' and parent_opening_id is null
    and dbms_lob.compare(description,to_clob('User description')) = 0;
  expect(l_count = 1,'Repeat must preserve existing opening fields and changed parent');
  select count(*) into l_count from orac_chess.chess_variation_v
  where name = 'User root' and variation_id = l_root and dbms_lob.compare(pgn,to_clob('1.d4 d5 *')) = 0;
  expect(l_count = 1,'Repeat must preserve existing root MAIN and user name/PGN');
  select count(*) into l_count from orac_chess.chess_content_source_v
  where creator = '__SEED_ACCEPTANCE_valid' and author = 'User author' and dbms_lob.compare(notes,to_clob('User notes')) = 0;
  expect(l_count = 1,'Repeat must preserve source author and notes');
  select count(*) into l_count from orac_chess.chess_video_v where video_id = l_id and title = 'User title' and duration_seconds = 12;
  expect(l_count = 1,'Repeat must preserve video fields');
  select count(*) into l_count from orac_chess.chess_opening_gambit_v
  where gambit_id = (select gambit_id from orac_chess.chess_gambit_v where name = '__SEED_ACCEPTANCE_valid_gambit');
  expect(l_count = 2,'Many-to-many catalogue associations must be retained exactly once');
"""
    for label, kwargs in [
        ("invalid_pgn", {"pgn": "1.e5 *"}),
        ("invalid_fen", {"pgn": "1.e4 *", "fen": "invalid FEN"}),
        ("missing_link", {"pgn": "1.e4 *", "missing": True}),
    ]:
        text += "  begin\n" + block(label, **kwargs) + f"""
    raise_application_error(-20999,'Expected {label} batch failure');
  exception
    when others then
      if sqlcode <> -20002 or instr(sqlerrm, '.csv: row ') = 0
      then
        raise;
      end if;
  end;
  select count(*) into l_count from orac_chess.chess_content_source_v where creator = '__SEED_ACCEPTANCE_{label}';
  expect(l_count = 0,'Failed {label} batch must roll back earlier source insertion');
  select count(*) into l_count from orac_chess.chess_opening_v where name in ('__SEED_ACCEPTANCE_{label}_child','__SEED_ACCEPTANCE_{label}_parent');
  expect(l_count = 0,'Failed {label} batch must roll back catalogue identities');
  select count(*) into l_count from orac_chess.chess_video_v where external_video_id = '__SEED_ACCEPTANCE_{label}';
  expect(l_count = 0,'Failed {label} batch must roll back video insertion');
"""
    return text + """  rollback to seed_acceptance;
  dbms_output.put_line('PASS: actual seed runtime, long PGN, edits preserved, links, invalid PGN/FEN and late failure atomicity');
exception
  when others then
    rollback;
    raise;
end;
/
"""


def main() -> int:
    """Generate or check the isolated acceptance SQL without accessing a database."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "db/acceptance/verify_seed_runtime.sql"
    content = generate_acceptance()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            logger.error("Generated acceptance SQL is stale: %s", path)
            return 1
    else:
        path.write_text(content, encoding="utf-8")
    logger.info("%s %s", "Checked" if args.check else "Generated", path)
    return 0


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
    raise SystemExit(main())
